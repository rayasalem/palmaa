#!/usr/bin/env node
/**
 * Report files over 500 lines (backend and frontend source).
 * Output: docs/FILES_OVER_500_LINES.md
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const THRESHOLD = 500;

const backendDirs = ['server'];
const frontendDirs = ['views', 'components', 'api', 'hooks', 'services'];
const backendExt = ['.js'];
const frontendExt = ['.ts', '.tsx'];

function countLines(filePath) {
  try {
    const content = fs.readFileSync(filePath, 'utf8');
    return content.split(/\r?\n/).length;
  } catch {
    return 0;
  }
}

function walk(dir, exts, results) {
  if (!fs.existsSync(dir)) return;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name !== 'node_modules' && e.name !== 'dist' && e.name !== 'build') walk(full, exts, results);
    } else if (exts.some((ext) => e.name.endsWith(ext))) {
      const lines = countLines(full);
      const relative = path.relative(ROOT, full);
      results.push({ path: relative, lines });
    }
  }
}

const backend = [];
const frontend = [];

for (const d of backendDirs) {
  const abs = path.join(ROOT, d);
  walk(abs, backendExt, backend);
}
for (const d of frontendDirs) {
  const abs = path.join(ROOT, d);
  walk(abs, frontendExt, frontend);
}

const over500 = (list) => list.filter((f) => f.lines > THRESHOLD).sort((a, b) => b.lines - a.lines);

const backendOver = over500(backend);
const frontendOver = over500(frontend);

let md = `# Files Over ${THRESHOLD} Lines\n\nGenerated by \`npm run report:large-files\`.\n\n`;
md += `## Backend (server/)\n\n| File | Lines |\n|------|-------|\n`;
for (const f of backendOver) {
  md += `| ${f.path} | ${f.lines} |\n`;
}
if (backendOver.length === 0) md += `| *(none)* | |\n`;

md += `\n## Frontend\n\n| File | Lines |\n|------|-------|\n`;
for (const f of frontendOver) {
  md += `| ${f.path} | ${f.lines} |\n`;
}
if (frontendOver.length === 0) md += `| *(none)* | |\n`;

const outPath = path.join(ROOT, 'docs', 'FILES_OVER_500_LINES.md');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, md, 'utf8');
console.log('Wrote', outPath);
console.log('Backend over 500:', backendOver.length);
console.log('Frontend over 500:', frontendOver.length);
